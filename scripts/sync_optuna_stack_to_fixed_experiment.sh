#!/usr/bin/env bash
# Rebuild My_creation/fixed_experiment/ as a **self-contained Optuna + train.py workspace**
# (same layout assumptions as My_creation/: SCRIPT_DIR = directory containing optuna_search_v2.py).
#
# Usage (from anywhere):
#   RESET=1 bash My_creation/scripts/sync_optuna_stack_to_fixed_experiment.sh
#
# Env:
#   RESET=1              rm -rf fixed_experiment before copy (recommended once).
#   OPTUNA_LOGS_MODE=none|4090D_restart|all
#                        none (default): do not copy logs/optuna (large).
#                        4090D_restart: rsync logs/optuna/4090D_restart only.
#                        all: rsync entire logs/optuna.
#   SKIP_WEIGHTS=1       skip deberta-v3-base and bert-base-chinese (for quick code-only sync).
#   SKIP_DATA=1         skip datasets/*.pkl

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
MY="$(cd "${SCRIPT_DIR}/.." && pwd)"
cd "${MY}"
FE="${MY}/fixed_experiment"
RESET="${RESET:-0}"
OPTUNA_LOGS_MODE="${OPTUNA_LOGS_MODE:-none}"
SKIP_WEIGHTS="${SKIP_WEIGHTS:-0}"
SKIP_DATA="${SKIP_DATA:-0}"

PY_FILES=(
  train.py
  optuna_search_v2.py
  deberta_infogate.py
  bert_infogate.py
  infogate_modules.py
  global_configs.py
  selection_utils.py
  simsv2_metrics.py
)

OPTUNA_SH=(
  run_optuna_4090d_restart.sh
  run_optuna_classify.sh
  run_optuna_ur_funny_v2.sh
)

if [[ "${RESET}" == "1" ]]; then
  echo "[sync] RESET=1: removing ${FE}"
  rm -rf "${FE}"
fi
mkdir -p "${FE}/scripts"

echo "[sync] copying Python stack -> ${FE}/"
for f in "${PY_FILES[@]}"; do
  cp -a "${MY}/${f}" "${FE}/"
done

for s in "${OPTUNA_SH[@]}"; do
  if [[ -f "${MY}/${s}" ]]; then
    cp -a "${MY}/${s}" "${FE}/"
  fi
done

shopt -s nullglob
for vf in "${MY}"/scripts/verify_*optuna*.py; do
  cp -a "${vf}" "${FE}/scripts/"
done

if [[ "${SKIP_DATA}" != "1" ]]; then
  echo "[sync] datasets/*.pkl"
  mkdir -p "${FE}/datasets"
  for p in mosi.pkl mosei.pkl simsv2.pkl; do
    if [[ -f "${MY}/datasets/${p}" ]]; then
      cp -a "${MY}/datasets/${p}" "${FE}/datasets/"
    else
      echo "[sync] warn: missing ${MY}/datasets/${p}" >&2
    fi
  done
else
  echo "[sync] SKIP_DATA=1: skip datasets"
fi

if [[ "${SKIP_WEIGHTS}" != "1" ]]; then
  echo "[sync] HF weights (rsync, may take a while)"
  mkdir -p "${FE}/deberta-v3-base" "${FE}/bert-base-chinese"
  if [[ -d "${MY}/deberta-v3-base" ]]; then
    rsync -a --delete --exclude='__pycache__' "${MY}/deberta-v3-base/" "${FE}/deberta-v3-base/"
  else
    echo "[sync] warn: missing ${MY}/deberta-v3-base" >&2
  fi
  if [[ -d "${MY}/bert-base-chinese" ]]; then
    rsync -a --delete --exclude='__pycache__' "${MY}/bert-base-chinese/" "${FE}/bert-base-chinese/"
  else
    echo "[sync] warn: missing ${MY}/bert-base-chinese" >&2
  fi
else
  echo "[sync] SKIP_WEIGHTS=1: skip HF dirs"
fi

case "${OPTUNA_LOGS_MODE}" in
  none)
    mkdir -p "${FE}/logs/optuna"
    echo "[sync] OPTUNA_LOGS_MODE=none: created empty ${FE}/logs/optuna (populate with COPY or run Optuna here)."
    ;;
  4090D_restart)
    if [[ -d "${MY}/logs/optuna/4090D_restart" ]]; then
      echo "[sync] rsync logs/optuna/4090D_restart (large)..."
      mkdir -p "${FE}/logs/optuna"
      rsync -a "${MY}/logs/optuna/4090D_restart/" "${FE}/logs/optuna/4090D_restart/"
    else
      echo "[sync] warn: ${MY}/logs/optuna/4090D_restart not found" >&2
      mkdir -p "${FE}/logs/optuna"
    fi
    ;;
  all)
    if [[ -d "${MY}/logs/optuna" ]]; then
      echo "[sync] rsync entire logs/optuna (can be very large)..."
      rsync -a "${MY}/logs/optuna/" "${FE}/logs/optuna/"
    else
      mkdir -p "${FE}/logs/optuna"
    fi
    ;;
  *)
    echo "OPTUNA_LOGS_MODE must be none|4090D_restart|all, got: ${OPTUNA_LOGS_MODE}" >&2
    exit 1
    ;;
esac

# Placeholder dirs Optuna drivers create (harmless if already exist)
mkdir -p "${FE}/checkpoints"

echo "[sync] done. du -sh:"
du -sh "${FE}" || true
echo "[sync] bundle root: ${FE}"

cat >"${FE}/README.md" <<'EOF'
# fixed_experiment (Optuna stack mirror)

This directory is generated by **`My_creation/scripts/sync_optuna_stack_to_fixed_experiment.sh`**.
It mirrors everything **Optuna + `train.py` subprocess** need under the same layout as `My_creation/`:

- Training / search code: `train.py`, `optuna_search_v2.py`, `*_infogate.py`, `infogate_modules.py`, `global_configs.py`, `selection_utils.py`, `simsv2_metrics.py`
- **Local HF weights**: `deberta-v3-base/`, `bert-base-chinese/`
- **Pickles**: `datasets/{mosi,mosei,simsv2}.pkl`
- **Drivers**: `run_optuna_4090d_restart.sh`, `run_optuna_classify.sh`, `run_optuna_ur_funny_v2.sh`
- **Verify helpers**: `scripts/verify_*_optuna_train_argv.py`
- **Logs / DBs** (optional copy): `logs/optuna/…` — see script `OPTUNA_LOGS_MODE`.

## How to (re)build

```bash
cd /path/to/My_creation
RESET=1 bash scripts/sync_optuna_stack_to_fixed_experiment.sh
# with gold logs only:
#   RESET=1 OPTUNA_LOGS_MODE=4090D_restart bash scripts/sync_optuna_stack_to_fixed_experiment.sh
```

## How to run Optuna from here

```bash
cd /path/to/My_creation/fixed_experiment
export PYTHON=/path/to/your/python   # optional; script defaults to ITHP5090 in run_optuna_4090d_restart.sh
./run_optuna_4090d_restart.sh phase1
```

`ROOT` in the launcher is **`$(pwd)`**, so DB paths and `--artefact_root` resolve under **this** tree. Warm-start flags that reference `phase1` / `phase2` DBs require those directories under `logs/optuna/4090D_restart/` (copy with `OPTUNA_LOGS_MODE=4090D_restart` or run phases in order).

## Next steps (your “再做修改”)

Typical follow-ups (not done by the sync script):

1. **Vendored patches** — e.g. `train.py` / `deberta_infogate.py` path tweaks, or HF meta workarounds; keep diffs small and documented here.
2. **`paper_repro_bundle/`** — if you still want a portable paper bundle, regenerate from `My_creation/` with `bash scripts/bundle_paper_repro_to_fixed_experiment.sh` (lives under `fixed_experiment/paper_repro_bundle/` after bundle run).
3. **Frozen single-trial launchers** — re-add `train_fixed_*.py` + `*_hparams.py` if you need argv-only repro without Optuna.

## Regenerate

Re-running the sync script with **`RESET=1`** replaces this entire directory.
EOF
